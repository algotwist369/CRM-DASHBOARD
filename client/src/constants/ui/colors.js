// Color utilities
export const COLOR_UTILITIES = {
  // Get color with opacity
  withOpacity: (color, opacity) => `${color}${Math.round(opacity * 255).toString(16).padStart(2, '0')}`,
  
  // Get color shade
  getShade: (color, shade) => COLORS[color.toUpperCase()]?.[shade] || color,
  
  // Get semantic color
  getSemantic: (category, variant) => SEMANTIC_COLORS[category]?.[variant] || COLORS.NEUTRAL[500],
  
  // Get theme color
  getTheme: (theme, color) => THEME_COLORS[theme]?.[color] || COLORS.NEUTRAL[500],
}

